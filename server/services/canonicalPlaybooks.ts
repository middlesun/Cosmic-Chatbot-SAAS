export type PlaybookDomain =
  | 'marriage'
  | 'synastry'
  | 'career'
  | 'wealth'
  | 'health'
  | 'mental'
  | 'timing'
  | 'foreign'
  | 'education'
  | 'progeny'
  | 'property'
  | 'litigation'
  | 'spirituality'
  | 'remedies'
  | 'learning'
  | 'relationships'
  | 'open';

export interface CanonicalPlaybookDef {
  id: string;
  domain: PlaybookDomain;
  title: string;
  shortLabel: string;
  defaultIntent: SutraIntentArchetype;
  requiredHouses: number[];
  requiredVargas: string[];
  requiredKpCusps: number[];
  requiredKarakas: string[];
  requiresTimingStack: boolean;
  requiresSynastry: boolean;
  formulaSlugs: string[];
  priorityDomain: string;
  clarifyIfMissing: string[];
  nextHops: string[];
}

interface PlaybookSeed {
  id: string;
  domain: PlaybookDomain;
  title: string;
  shortLabel: string;
  defaultIntent: SutraIntentArchetype;
  requiredHouses: number[];
  requiredVargas: string[];
  requiredKpCusps: number[];
  requiredKarakas: string[];
  requiresTimingStack: boolean;
  requiresSynastry?: boolean;
  formulaSlugs: string[];
  priorityDomain: string;
  clarifyIfMissing?: string[];
  nextHops: string[];
}

function buildPlaybook(seed: PlaybookSeed): CanonicalPlaybookDef {
  return {
    ...seed,
    requiresSynastry: Boolean(seed.requiresSynastry),
    clarifyIfMissing: seed.clarifyIfMissing || [],
  };
}

